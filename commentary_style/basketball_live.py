def _render_live_spoken_patterns() -> str:
    return "\n".join(
        f"{category}：{' / '.join(patterns)}"
        for category, patterns in LIVE_SPOKEN_PATTERNS.items()
    )


class BasketballLiveCommentarySkill:
    """Project-internal style pack for natural Chinese basketball commentary."""

    name = "human_basketball_live"
    label = "活人感篮球解说 Skill"

    def observation_rules(self) -> str:
        return (
            "观察阶段只提供事实材料，不追求文采。按时间记录球权、连续动作、可见结果、"
            "现场声音和置信度；把球权变化、明确进球、仅有出手、画面停顿分开写。"
            "声音不能单独证明犯规，画内字幕和已有解说也不能替代画面证据。"
        )

    def planner_rules(
        self,
        duration: float,
        beat_count: int,
        minimum_chars: int,
        target_chars: int,
        maximum_chars: int,
    ) -> str:
        long_count = max(1, math.ceil(beat_count * 0.3))
        short_max = min(max(1, math.floor(beat_count * 0.3)), beat_count - long_count)
        spoken_patterns = _render_live_spoken_patterns()
        return f"""
活人感篮球解说 Skill

说话位置
你就在场边跟着这段回合说话。手里只有音画观察和用户确认的信息。看清多少就说多少，不用空话补满，也不把不确定的结果说成确定。

自然句长
这段 {duration:.1f} 秒视频写 {beat_count} 个开口时间点，总口播控制在 {minimum_chars}–{maximum_chars} 个汉字，接近 {target_chars} 字。
beat 是一段连续口播开始的时间，不是必须立刻停下的五字标题。至少 {long_count} 段写成 13–22 字的完整口语句，交代球权、动作或防守关系；最多 {short_max} 段可以是 4–8 字的动作短句，只留给抢断、起步、出手和明确结果附近。其余段落以 9–16 字为主。短句和完整句交替，禁止所有段落同长，禁止连续三段短句，禁止把每段都写成“五字，五字”的整齐对仗。

回合承接
球权没变时，后一句自然接住前一句，不要每句都重新说颜色、号码和“某队持球”。球权明确易手、篮板被控制或重新发球时，才重新点明持球方。可以有正常的承接、补充和即时反应，不能写成逐条动作清单。

现场口语动作
先在“动作报点、接住上一动作、空间或防守判断、结果爆点、结果后的短余韵”里选择当下真正需要的一种说话意图，再写句子。以下全部是项目原创的节奏样例，用来学习真人看球时如何起句、接话和收声，不是逐条照抄的固定口号：
{spoken_patterns}
这些短促说法必须由当前事件或相邻同一回合的证据解锁。普通传球不能擅自说“再转一手”，普通突破不能擅自说“过掉了”，仅有出手不能说“有了”或“进了”。每个 beat 最多放一个短促反应，短反应后面要接可听懂的动作、结果或余韵；只有抢断、封盖、明确命中等高潮可以单独短喊一次。相邻同类事件要换起手，不能连续重复“持球人继续往里突破”“完成出手”“打进”这一套。连续多个明确命中时，在“有了、进了、命中、打进”之间轮换起手，并把余韵分别落在机会把握、动作节奏、处理选择或防守压力上；没有对应证据时只换结果起手，不补投篮类型。活人感来自对动作的即时反应，不来自乱加“哎哟、嚯、兄弟们、家人们”或故意说错话。

专业术语
术语跟着动作走，不把术语当成必须完成的清单。连续画面明确时，可以自然使用强弱侧转移、突分、击地传球、口袋传球、手递手、传切、空切、面框单打、低位背身、定点接球、变向、胯下、背后运球、转身、沿底线突破、杀入篮下、挡拆、无球掩护、顺下、外弹、换防、夹击、协防、补防、轮转、扑防、沉退、护框、卡位、快攻、一条龙、多打少、急停跳投、接球投、后撤步、后仰、抛投、勾手、擦板、上篮、反篮、欧洲步、扣篮、补篮和空中接力。脚与三分线都看清并通过局部逐帧复核才说三分，动作轮廓看不清就退回“突破、传球、出手、篮板”等基础表达。一句只放一个最有辨识度的术语，不能堆成战术报告。助攻、失误、造犯规、2+1、压哨和绝杀是统计或裁判结论，不能仅凭一个动作镜头就下结论。

夸赞与氛围
夸赞要接在眼前的好动作或明确结果上。普通的好处理可以说“传得真及时”“这一步很漂亮”“处理得够果断”；明确命中、封盖或抢断后可以短促地接“好球”“漂亮”“好帽”“防得真好”，也可以把评价落到“把握得稳”“处理得干净”“机会没有浪费”。只有局部逐帧复核清楚显示出手过程中的身体接触或强对抗时，才能说“这球够硬”“顶着对抗打进”。普通扑防和贴防最多说“面对干扰还能收下”。全片大约每三个 beat 最多有一处显性夸赞，裸喊“好球”全片最多一次；后面的夸赞必须换评价落点，不能只是“好球、漂亮、真好”轮番喊，也不能连续三句都在喊。“关键、绝杀、压哨、高难度、无解”会额外改变事实和强度判断，没有对应画面或用户确认就不说。

情绪弧线
开头先把球权和防守位置说清，动作连续时缩短并提速，结果得到画面确认后只爆发一次，随后用一条自然余韵收住。结果不明就停在“出手”或眼前动作，不强造命中和总结。普通推进不用感叹号，不能每一句都重新起调。

口语完整
主语、动作和关系要能听懂。禁止“快速推进传、找位空切跑、接球稳、投篮偏、断球下、补防扰、打进篮、命中敌”这类为凑字数压坏语法的残句。不要写“根据画面、镜头给到、我们可以看到、精彩时刻、完成终结、火力全开、悬念拉满”等模板话。
“漂亮”“好球”“厉害”不能脱离动作或结果单独占一段，也不能写“帅爆了”。视频结尾只跟着最后一个真实回合自然收住，不加“感谢收看、下次再见、欢迎关注”这类节目片尾话。

事实边界
只能改措辞、分段、停连和情绪，不能新增动作、比分、分值、姓名、队名、号码、进球结果或判罚。哨音和尖锐声音只能帮助复核邻近画面，不能单独推出犯规、责任球员或罚球。不得模仿任何真人解说员的声纹、名句、固定口头禅或个人标志。
""".strip()

    def rewrite_rules(
        self,
        issues: Sequence[LintIssue],
        beat_count: int,
        minimum_chars: int,
        target_chars: int,
        maximum_chars: int,
    ) -> str:
        issue_text = "、".join(issue.code for issue in issues) or "GENERAL_CADENCE"
        return f"""
启用活人感篮球解说 Skill 修订。当前问题为 {issue_text}。
保持已有事实和时间顺序，只修措辞与分段。输出 {beat_count} 段，总字数 {minimum_chars}–{maximum_chars}，接近 {target_chars} 字。
打散整齐句长，补回正常主谓和动作关系。至少五分之一段落达到 13 字，动作高潮可以短，连续短句不得超过两段。不要用空泛评价补字，不要把“出手”改成“打进”，不要新增比分、人物、队名、分值或判罚。
每段都要能被人自然说出口。禁止“五字，五字”排队，也禁止接球稳、投篮偏、断球下、补防扰、抛投出、打进篮这一类残句。
把连续重复的“持球人继续往里突破、完成出手、打进”改成有承接的现场口语，但事件事实必须保持不变。连续命中在“有了、进了、命中、打进”之间换起手，裸喊“好球”全片最多一次；再次夸赞要改说当前动作为什么好。删掉单独的“漂亮、好球、帅爆了”和“感谢收看、下次再见”；夸赞必须和对应动作或明确结果说在一起。
""".strip()

    def tts_group_rules(self, has_result: bool, is_first: bool, is_last: bool) -> str:
        rules = (
            "把这一组当成同一个人连续看球时说的一口话，让各句一口气自然衔接。完整句正常说，动作短句才提速，"
            "不要按相同拍子逐条念，不能把每个句号都读成一次独立播报。"
        )
        if has_result:
            rules += "确认结果的位置只爆发一次，“好球”或“漂亮”要和结果连成一次自然反应，后面的余韵马上回落。"
        if is_first:
            rules += "开头直接进入球权和动作，不念标题。"
        if is_last:
            rules += "结尾像现场反应自然收住，不做宣传式总结。"
        return rules


